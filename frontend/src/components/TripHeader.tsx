"use client";

import React, { useState } from "react";
import {
  Calendar,
  Users,
  MapPin,
  CheckCircle2,
  Share2,
  Download,
  Copy,
  Check,
  Sparkles,
  Zap,
} from "lucide-react";
import { useTripStore } from "../store/useTripStore";

export function TripHeader() {
  const { trip } = useTripStore();
  const [copied, setCopied] = useState(false);

  if (!trip) return null;

  const handleShare = () => {
    if (navigator.clipboard) {
      navigator.clipboard.writeText(window.location.href);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  const handleDownload = () => {
    const textContent = `${trip.title}\n\nOVERVIEW:\n${trip.overview}\n\nESTIMATED BUDGET:\nTotal: ${trip.budget.currency_symbol}${trip.budget.estimated_total.toLocaleString()} (${trip.budget.status_label})\nTarget: ${trip.budget.currency_symbol}${trip.budget.user_budget.toLocaleString()}\n\nDESTINATIONS:\n${trip.destinations.join(", ")}\n\nDATES:\n${trip.travel_dates.formatted}\n\nITINERARY HIGHLIGHTS:\n${trip.itinerary.map((d) => `Day ${d.day} (${d.destination}): ${d.title}\n- ${d.summary}`).join("\n\n")}\n\nGenerated by Wayfarer AI Travel Agent`;

    const blob = new Blob([textContent], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${trip.title.toLowerCase().replace(/[^a-z0-9]/g, "-")}-plan.txt`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="bg-white rounded-2xl border border-stone-200/80 p-5 sm:p-7 shadow-xs">
      <div className="flex flex-col lg:flex-row lg:items-center lg:justify-between gap-5">
        {/* Left: Title & Badges */}
        <div className="space-y-3">
          <div className="flex flex-wrap items-center gap-2">
            <span className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-xs font-semibold bg-emerald-50 text-emerald-800 border border-emerald-200">
              <CheckCircle2 className="h-3.5 w-3.5 text-emerald-600" />
              {trip.status || "Verified Plan"}
            </span>

            {trip.latency && (
              <span
                title={`Pipeline Latency: ${trip.latency.formatted} (${trip.latency.total_latency_ms} ms) with parallel multitasking`}
                className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-xs font-semibold bg-amber-50 text-amber-900 border border-amber-200/80 shadow-2xs"
              >
                <Zap className="h-3 w-3 text-amber-600 fill-amber-500" />
                <span>{trip.latency.formatted}</span>
                <span className="hidden sm:inline text-amber-700/80 font-normal">· Parallel Concurrency</span>
              </span>
            )}

            {/* Destination tags */}
            {trip.destinations.map((dest, idx) => (
              <span
                key={`header-dest-${dest}-${idx}`}
                className="inline-flex items-center gap-1 px-2.5 py-0.5 rounded-full text-xs font-medium bg-stone-100 text-stone-700"
              >
                <MapPin className="h-3 w-3 text-stone-500" />
                {dest}
              </span>
            ))}
          </div>

          <h2 className="text-2xl sm:text-3xl font-semibold text-stone-900 tracking-tight">
            {trip.title}
          </h2>

          <div className="flex flex-wrap items-center gap-4 text-xs sm:text-sm text-stone-500 font-medium">
            <div className="flex items-center gap-1.5">
              <Calendar className="h-4 w-4 text-[#1B4332]" />
              <span>{trip.travel_dates.formatted}</span>
            </div>
            <span>•</span>
            <div className="flex items-center gap-1.5">
              <Users className="h-4 w-4 text-[#1B4332]" />
              <span>{trip.travelers.label}</span>
            </div>
            <span>•</span>
            <div className="flex items-center gap-1.5">
              <span className="font-semibold text-stone-900">
                {trip.budget.currency_symbol}
                {trip.budget.estimated_total.toLocaleString()}
              </span>
              <span className="text-emerald-700 font-normal">
                ({trip.budget.status_label})
              </span>
            </div>
          </div>
        </div>

        {/* Right: Actions */}
        <div className="flex items-center gap-2 self-start lg:self-center">
          <button
            onClick={handleShare}
            className="flex items-center gap-1.5 px-3.5 py-2 text-xs font-medium text-stone-700 bg-white border border-stone-200 rounded-xl hover:bg-stone-50 transition-colors shadow-2xs cursor-pointer"
          >
            {copied ? (
              <>
                <Check className="h-3.5 w-3.5 text-emerald-600" />
                <span>Link Copied!</span>
              </>
            ) : (
              <>
                <Share2 className="h-3.5 w-3.5 text-stone-500" />
                <span>Share Plan</span>
              </>
            )}
          </button>

          <button
            onClick={handleDownload}
            className="flex items-center gap-1.5 px-3.5 py-2 text-xs font-medium text-white bg-[#1B4332] hover:bg-[#2D6A4F] rounded-xl transition-colors shadow-2xs cursor-pointer"
          >
            <Download className="h-3.5 w-3.5 text-emerald-100" />
            <span>Download Plan</span>
          </button>
        </div>
      </div>
    </div>
  );
}

